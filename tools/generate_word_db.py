def main():
    """创建 CET-4 词库 SQLite 数据库"""

    # 确保 stdout 支持 Unicode（Windows GBK 环境）
    if sys.platform == "win32":
        try:
            sys.stdout.reconfigure(encoding="utf-8")
        except Exception:
            pass

    # 构建词表并自动分配 seq
    words = []
    for i, (word, phonetic, pos, meaning, example) in enumerate(WORD_DATA, 1):
        words.append({
            "word": word,
            "phonetic": phonetic,
            "pos": pos,
            "meaning": meaning,
            "example": example,
            "book": "cet4",
            "seq": i,
        })

    # 确定输出路径
    script_dir = os.path.dirname(os.path.abspath(__file__))
    project_dir = os.path.dirname(script_dir)
    db_dir = os.path.join(project_dir, "assets")
    os.makedirs(db_dir, exist_ok=True)
    db_path = os.path.join(db_dir, "cet4.db")

    # 创建数据库
    conn = sqlite3.connect(db_path)
    c = conn.cursor()

    # 建表
    c.execute("DROP TABLE IF EXISTS words")
    c.execute("""
        CREATE TABLE words (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            word TEXT NOT NULL,
            phonetic TEXT,
            pos TEXT,
            meaning TEXT,
            example TEXT,
            book TEXT DEFAULT 'cet4',
            seq INTEGER
        )
    """)

    # 插入数据
    c.executemany(
        "INSERT INTO words (word, phonetic, pos, meaning, example, book, seq) "
        "VALUES (?, ?, ?, ?, ?, ?, ?)",
        [(w["word"], w["phonetic"], w["pos"], w["meaning"],
          w["example"], w["book"], w["seq"]) for w in words]
    )

    # 创建索引
    c.execute("CREATE INDEX IF NOT EXISTS idx_word ON words(word)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_book ON words(book)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_seq ON words(seq)")

    conn.commit()

    # 输出统计信息
    total = len(words)
    print(f"Database created: {db_path}")
    print(f"Total words: {total}")

    # 按首字母统计
    c.execute("""
        SELECT UPPER(SUBSTR(word,1,1)), COUNT(*)
        FROM words
        GROUP BY UPPER(SUBSTR(word,1,1))
        ORDER BY UPPER(SUBSTR(word,1,1))
    """)
    print("Distribution by first letter:")
    for letter, count in c.fetchall():
        print(f"  {letter}: {count}")

    # 按词性统计
    c.execute("SELECT pos, COUNT(*) FROM words GROUP BY pos ORDER BY COUNT(*) DESC LIMIT 10")
    print("Top 10 parts of speech:")
    for pos, count in c.fetchall():
        print(f"  {pos}: {count}")

    # 显示前5条和后5条记录
    print("\nFirst 5 words:")
    c.execute("SELECT word, phonetic, pos, meaning FROM words ORDER BY seq LIMIT 5")
    for row in c.fetchall():
        print(f"  {row[0]} {row[1]} {row[2]} {row[3]}")

    print("\nLast 5 words:")
    c.execute("SELECT word, phonetic, pos, meaning FROM words ORDER BY seq DESC LIMIT 5")
    for row in c.fetchall():
        print(f"  {row[0]} {row[1]} {row[2]} {row[3]}")

    conn.close()
    print("\nDone!")


if __name__ == "__main__":
    main()
